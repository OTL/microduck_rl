"""QDD biped velocity (walking) environment — Mjlab-Velocity-Flat-QddBiped.

A different robot from the microduck: 6.48 kg, ~0.52 m tall, 10 quasi-direct-
drive joints ({l,r}_{hip_yaw, hip_roll, hip_pitch, knee, ankle_pitch}), no ankle
roll (lateral balance must be dynamic, like Disney BDX / Open Duck Mini), flat
150 x 70 mm feet centred under the ankle. Robot model:
robot/qdd_biped_constants.py + robot/qdd_biped/qdd_biped.xml.

Recipe = the microduck velocity recipe (microduck_velocity_env_cfg.py), ported
to this robot, keeping its sim2real choices:
  - actor obs = what the real robot has: IMU gyro + projected gravity (with a
    per-env IMU mounting misalignment and 0-1 step delay), joint pos (with
    per-env encoder bias) / vel, last action, twist command. NO base lin vel in
    the actor (critic-only, privileged), no height scan.
  - unfiltered actions (no EMA), obs normalisation baked into the ONNX by
    scripts/export.py.
  - fixed modest command ranges + explicit standing (curriculum-ramped) and
    turn-in-place buckets, tracking + upright + variable-posture + gait/feet
    terms, curriculum-ramped action-rate smoothing.
Differences from microduck (different robot, not part of the 61-D microduck
policy family, so the actor obs is 3+3+10+10+10+3 (+2 gait phase) = 41-D, no head/body slots):
  - built-in MuJoCo position PD actuators (the drivers run PD in MIT mode)
    instead of BAM; Kp/Kd/effort limits per motor in qdd_biped_constants.py,
    with PD-gain / effort-limit DR and 0-10 ms command latency,
  - pose-dependent knee limit knee_max(hip_pitch) from robot/model.py: cost
    term + termination,
  - falls terminate on torso tilt > 60 deg, torso height < 0.20 m or any
    non-foot ground contact.

Human-like gait (2026-10): a gait clock (tasks/mdp.py GaitClockCommand,
period GAIT_PERIOD_S, paused while standing) is appended to the actor obs as
[sin, cos] (39 -> 41-D) and drives a contact-schedule reward (alternating
single support, short double support), a swing-foot height trajectory
(GAIT_SWING_HEIGHT peak, sine profile), flat-foot touchdown, low touchdown
velocity / slip, lateral foot spacing and hip yaw/roll regularisation, plus a
left-right mirror loss (symmetry.py qdd_biped_symmetry). The policy I/O
contract for the real robot is robot/qdd_biped/policy_io.json, generated by
build_policy_io() below (tests check it against the live env).
"""

import math
from copy import deepcopy

NUM_STEPS_PER_ENV = 24

TURN_IN_PLACE_FRACTION = 0.15
# Forward-only envs (vx in [0.3, 0.5], vy = wz = 0; mjlab rel_forward_envs). The
# robot's main use is walking straight ahead; the template default was 0.2.
FORWARD_ENVS_FRACTION = 0.3

# Velocity tracking. The coarse kernel alone (std 0.25 m/s) still pays 70% of
# the reward for 0.44 m/s at a 0.5 m/s command, and gait1 (nominal training
# sim) settled there: 0.284 / 0.441 m/s at 0.3 / 0.5 commands. A second, fine
# planar kernel (std 0.1 m/s: same miss -> 70% of it, 0.12 m/s miss -> 24%)
# makes the last few cm/s worth more than the gait-shaping costs.
LIN_VEL_STD = 0.25  # m/s, coarse (learning signal from the start)
LIN_VEL_FINE_STD = 0.10  # m/s, fine (xy only: no penalty on the torso bob)
# gait3: 1.5 -> 1.2 (gait2 tracked 0.306 / 0.500 but shuffled its feet: the
# fine kernel out-earned the swing-height term).
LIN_VEL_FINE_WEIGHT = 1.2
ANG_VEL_STD = 0.5  # rad/s, coarse
# Fine yaw-rate kernel (gait3): gait2 turned in place at 0.70 rad/s for 0.8,
# which the coarse kernel still paid 96% for.
ANG_VEL_FINE_STD = 0.15  # rad/s
ANG_VEL_FINE_WEIGHT = 1.0

# Play mode (export / yatai video): nominal robot, no DR / pushes / noise, and a
# fixed readable command schedule ((t_start_s, vx, vy, wz), looping).
PLAY_COMMAND_SCHEDULE = (
    (0.0, 0.0, 0.0, 0.0),  # stand
    (1.0, 0.3, 0.0, 0.0),  # walk
    (5.0, 0.5, 0.0, 0.0),  # faster (top of the trained range)
    (9.0, 0.0, 0.0, 0.8),  # turn in place (left)
    (12.0, 0.0, 0.0, 0.0),  # stop
)
PLAY_SCHEDULE_PERIOD_S = 15.0

# Commands (0.5 m robot, 0.13 m links)
LIN_VEL_X_RANGE = (-0.3, 0.5)
LIN_VEL_Y_RANGE = (-0.2, 0.2)
ANG_VEL_Z_RANGE = (-1.0, 1.0)

# Domain randomization
ENABLE_COM_RANDOMIZATION = True
ENABLE_MASS_INERTIA_RANDOMIZATION = True
ENABLE_PD_GAIN_RANDOMIZATION = True
ENABLE_EFFORT_LIMIT_RANDOMIZATION = True
ENABLE_ARMATURE_RANDOMIZATION = True
ENABLE_JOINT_FRICTION_RANDOMIZATION = True
ENABLE_VELOCITY_PUSHES = True
ENABLE_IMU_ORIENTATION_RANDOMIZATION = True
ENABLE_ENCODER_BIAS = True

COM_RANDOMIZATION_RANGE = {0: (-0.02, 0.02), 1: (-0.015, 0.015), 2: (-0.02, 0.02)}  # torso, m
MASS_INERTIA_RANDOMIZATION_RANGE = (0.9, 1.1)  # torso mass+inertia scale (battery/electronics)
KP_RANDOMIZATION_RANGE = (0.85, 1.15)
KD_RANDOMIZATION_RANGE = (0.8, 1.2)
EFFORT_LIMIT_RANDOMIZATION_RANGE = (0.8, 1.05)  # battery sag / driver current limit
ARMATURE_RANDOMIZATION_RANGE = (0.8, 1.2)  # rotor inertia is an estimate
JOINT_FRICTION_RANDOMIZATION_RANGE = (0.5, 2.0)  # x XML frictionloss 0.05 Nm
FOOT_FRICTION_RANGE = (0.4, 1.2)
VELOCITY_PUSH_INTERVAL_S = (3.0, 6.0)
VELOCITY_PUSH_RANGE = (-0.3, 0.3)  # m/s, x and y
IMU_ORIENTATION_RANDOMIZATION_ANGLE = 3.0  # deg, random axis, constant per env
ENCODER_BIAS_RANGE = (-0.01, 0.01)  # rad; absolute encoders on the QDD output

# Knee limit
KNEE_LIMIT_MARGIN = 0.05  # rad: cost starts 3 deg before knee_max(hip_pitch)
KNEE_LIMIT_TERMINATION_TOL = 0.15  # rad: terminate 8.6 deg past knee_max

# Gait clock / human-like gait
# Period: Froude-scaled human cadence (~1.1 s stride at 0.9 m leg) for a 0.26 m
# leg is ~0.6 s; 0.64 s = exactly 32 policy steps at 50 Hz. Fixed (not
# randomised) so the real-robot clock is identical to training.
GAIT_PERIOD_S = 0.64
GAIT_SWING_FRACTION = 0.4  # per leg; 2 x (0.5 - 0.4) * period = 2 x 64 ms double support
GAIT_ACTIVE_THRESHOLD = 0.05  # |v_xy| + |w_z| above this -> clock runs, else paused
GAIT_SWING_HEIGHT = 0.05  # m sole clearance at mid-swing (sine profile)
GAIT_HEIGHT_STD = 0.03  # m, swing-height tracking kernel (0.02 left no gradient: gait1 swung 1.3 cm, not 5)
GAIT_SWING_HEIGHT_WEIGHT = 2.0  # gait3: 1.0 -> 2.0 (gait2 swung 0.6 cm on average)
# One-sided minimum clearance during swing: min * sin(pi * progress), linear
# cost on the shortfall (3 cm short at mid-swing -> 0.3/step).
GAIT_MIN_CLEARANCE = 0.035  # m
GAIT_MIN_CLEARANCE_WEIGHT = -10.0
# Square stance at a stop (gait clock paused): feet side by side, equal hip
# pitch, equal load, default pose. gait2 stopped mid-stride (hip pitch 0.18 rad
# apart) and a bow started from there yawed ~7 deg.
STAND_SQUARE_WEIGHT = 2.0
STAND_OFFSET_STD = 0.02  # m, fore-aft l-r sole offset
STAND_HIP_PITCH_STD = 0.05  # rad, l-r hip pitch difference
STAND_LOAD_STD = 0.15  # left share of the sole force vs 0.5
STAND_POSE_STD = 0.2  # sqrt(sum of squared joint deviations), rad
# The clock stops wherever the stride was (the controller does the same: it
# only advances while the command is active), so for this long after a stop
# the contact schedule does not insist on both feet down: one settling step
# is allowed.
GAIT_STOP_SETTLE_S = 0.6
FOOT_TARGET_HEIGHT = GAIT_SWING_HEIGHT  # mjlab foot_swing_height (peak at landing)
FEET_LATERAL_SPACING = (0.08, 0.20)  # m, l-r sole offset in the heading frame (hips 0.13 apart)
SYMMETRY_MIRROR_LOSS = True

from mjlab.envs import ManagerBasedRlEnvCfg
from mjlab.envs.mdp import dr
from mjlab.envs.mdp.actions import JointPositionActionCfg
from mjlab.managers import (
    CurriculumTermCfg,
    EventTermCfg,
    ObservationTermCfg,
    RewardTermCfg,
    TerminationTermCfg,
)
from mjlab.managers.scene_entity_config import SceneEntityCfg
from mjlab.rl import RslRlModelCfg, RslRlOnPolicyRunnerCfg
from mjlab.sensor import (
    ContactMatch,
    ContactSensorCfg,
    ObjRef,
    RingPatternCfg,
    TerrainHeightSensorCfg,
)
from mjlab.tasks.velocity import mdp
from mjlab.tasks.velocity.mdp import UniformVelocityCommandCfg
from mjlab.tasks.velocity.velocity_env_cfg import make_velocity_env_cfg
from mjlab.utils.noise import UniformNoiseCfg as Unoise

from mjlab_microduck.robot.qdd_biped_constants import (
    FOOT_GEOMS,
    FOOT_SITES,
    QDD_ACTION_SCALE,
    QDD_JOINT_NAMES,
    TORSO_BODY,
    get_qdd_biped_robot_cfg,
)
from mjlab_microduck.tasks import mdp as microduck_mdp
from mjlab_microduck.tasks.symmetry import QDD_SYMMETRY_CFG, PpoWithSymmetryCfg


def make_qdd_biped_velocity_env_cfg(play: bool = False) -> ManagerBasedRlEnvCfg:
    """Flat-ground velocity tracking for the QDD biped."""

    feet_ground_cfg = ContactSensorCfg(
        name="feet_ground_contact",
        primary=ContactMatch(mode="geom", pattern=r"^(l_foot_collision|r_foot_collision)$", entity="robot"),
        secondary=ContactMatch(mode="body", pattern="terrain"),
        fields=("found", "force"),
        reduce="netforce",
        num_slots=1,
        track_air_time=True,
    )
    self_collision_cfg = ContactSensorCfg(
        name="self_collision",
        primary=ContactMatch(mode="subtree", pattern=TORSO_BODY, entity="robot"),
        secondary=ContactMatch(mode="subtree", pattern=TORSO_BODY, entity="robot"),
        fields=("found", "force"),
        reduce="none",
        num_slots=1,
        history_length=4,
    )
    # Anything but the soles touching the ground = fall (shins/knees included).
    body_ground_cfg = ContactSensorCfg(
        name="body_ground_contact",
        primary=ContactMatch(
            mode="geom",
            pattern=r"^(torso_collision|torso_deck_collision|(l|r)_(thigh|knee_motor|shank)_collision)$",
            entity="robot",
        ),
        secondary=ContactMatch(mode="body", pattern="terrain"),
        fields=("found",),
        reduce="none",
        num_slots=1,
    )
    foot_height_scan_cfg = TerrainHeightSensorCfg(
        name="foot_height_scan",
        frame=tuple(ObjRef(type="site", name=s, entity="robot") for s in FOOT_SITES),
        pattern=RingPatternCfg.single_ring(radius=0.06, num_samples=4),
        ray_alignment="yaw",
        max_distance=1.0,
        exclude_parent_body=True,
        include_geom_groups=(0,),
        debug_vis=False,
    )

    cfg = make_velocity_env_cfg()

    # --- Scene -----------------------------------------------------------------
    cfg.scene.entities = {"robot": get_qdd_biped_robot_cfg()}
    cfg.scene.sensors = (feet_ground_cfg, self_collision_cfg, body_ground_cfg, foot_height_scan_cfg)
    cfg.scene.terrain.terrain_type = "plane"
    cfg.scene.terrain.terrain_generator = None
    cfg.viewer.body_name = TORSO_BODY
    cfg.viewer.distance = 1.5

    # --- Actions -----------------------------------------------------------------
    joint_pos_action = cfg.actions["joint_pos"]
    assert isinstance(joint_pos_action, JointPositionActionCfg)
    joint_pos_action.scale = QDD_ACTION_SCALE

    # --- Commands ----------------------------------------------------------------
    command: UniformVelocityCommandCfg = deepcopy(cfg.commands["twist"])
    command.rel_standing_envs = 0.05  # ramped by the standing_envs curriculum
    command.rel_heading_envs = 0.0
    command.ranges.lin_vel_x = LIN_VEL_X_RANGE
    command.ranges.lin_vel_y = LIN_VEL_Y_RANGE
    command.ranges.ang_vel_z = ANG_VEL_Z_RANGE
    command.viz.z_offset = 0.6
    cfg.commands["twist"] = microduck_mdp.VelocityCommandCommandOnlyCfg(**vars(command))
    cfg.commands["twist"].rel_turn_in_place_envs = TURN_IN_PLACE_FRACTION
    cfg.commands["twist"].rel_forward_envs = FORWARD_ENVS_FRACTION
    # Gait clock: must come AFTER "twist" (reads the updated twist command).
    cfg.commands["gait"] = microduck_mdp.GaitClockCommandCfg(
        velocity_command_name="twist",
        period_s=GAIT_PERIOD_S,
        swing_fraction=GAIT_SWING_FRACTION,
        active_threshold=GAIT_ACTIVE_THRESHOLD,
    )

    # --- Rewards -----------------------------------------------------------------
    cfg.rewards["track_linear_velocity"].weight = 2.0
    cfg.rewards["track_linear_velocity"].params["std"] = LIN_VEL_STD
    cfg.rewards["track_linear_velocity_fine"] = RewardTermCfg(
        func=microduck_mdp.track_lin_vel_xy_exp,
        weight=LIN_VEL_FINE_WEIGHT,
        params={"command_name": "twist", "std": LIN_VEL_FINE_STD},
    )
    cfg.rewards["track_angular_velocity"].weight = 2.0
    cfg.rewards["track_angular_velocity"].params["std"] = ANG_VEL_STD
    cfg.rewards["track_angular_velocity_fine"] = RewardTermCfg(
        func=microduck_mdp.track_ang_vel_z_exp,
        weight=ANG_VEL_FINE_WEIGHT,
        params={"command_name": "twist", "std": ANG_VEL_FINE_STD},
    )

    cfg.rewards["upright"].params["asset_cfg"].body_names = (TORSO_BODY,)
    cfg.rewards["upright"].weight = 2.0
    cfg.rewards["upright"].params["std"] = math.sqrt(0.05)

    # Posture around the 45 deg crouch. hip_roll is NOT tight while walking: with
    # no ankle roll the lateral weight shift has to come from the hips.
    cfg.rewards["pose"].params["std_standing"] = {
        r".*hip_yaw.*": 0.1,
        r".*hip_roll.*": 0.08,
        r".*hip_pitch.*": 0.15,
        r".*knee.*": 0.15,
        r".*ankle.*": 0.1,
    }
    std_walking = {
        r".*hip_yaw.*": 0.25,
        r".*hip_roll.*": 0.15,
        r".*hip_pitch.*": 0.4,
        r".*knee.*": 0.4,
        r".*ankle.*": 0.3,
    }
    cfg.rewards["pose"].params["std_walking"] = std_walking
    cfg.rewards["pose"].params["std_running"] = std_walking
    cfg.rewards["pose"].params["walking_threshold"] = 0.05
    cfg.rewards["pose"].weight = 1.0

    cfg.rewards["body_ang_vel"].params["asset_cfg"].body_names = (TORSO_BODY,)
    cfg.rewards["body_ang_vel"].weight = -0.05
    cfg.rewards["angular_momentum"].weight = -0.02

    # --- Gait (clock-driven, human-like) ---
    # The clock replaces the free-form air_time / velocity-weighted clearance
    # terms of the template (they reward any stepping pattern).
    cfg.rewards.pop("air_time", None)
    cfg.rewards.pop("foot_clearance", None)
    feet = SceneEntityCfg("robot", site_names=FOOT_SITES)
    cfg.rewards["gait_contact"] = RewardTermCfg(
        func=microduck_mdp.gait_contact_schedule,
        weight=1.5,
        params={"sensor_name": feet_ground_cfg.name, "command_name": "gait", "settle_s": GAIT_STOP_SETTLE_S},
    )
    cfg.rewards["gait_swing_height"] = RewardTermCfg(
        func=microduck_mdp.gait_foot_height_tracking,
        weight=GAIT_SWING_HEIGHT_WEIGHT,
        params={
            "swing_height": GAIT_SWING_HEIGHT,
            "std": GAIT_HEIGHT_STD,
            "command_name": "gait",
            "asset_cfg": deepcopy(feet),
        },
    )
    cfg.rewards["swing_clearance"] = RewardTermCfg(
        func=microduck_mdp.gait_swing_clearance_deficit,
        weight=GAIT_MIN_CLEARANCE_WEIGHT,
        params={"min_height": GAIT_MIN_CLEARANCE, "command_name": "gait", "asset_cfg": deepcopy(feet)},
    )
    cfg.rewards["stand_square"] = RewardTermCfg(
        func=microduck_mdp.stand_square_stance,
        weight=STAND_SQUARE_WEIGHT,
        params={
            "sensor_name": feet_ground_cfg.name,
            "offset_std": STAND_OFFSET_STD,
            "hip_pitch_std": STAND_HIP_PITCH_STD,
            "load_std": STAND_LOAD_STD,
            "pose_std": STAND_POSE_STD,
            "command_name": "gait",
            "asset_cfg": deepcopy(feet),
        },
    )
    cfg.rewards["foot_swing_height"].params["target_height"] = FOOT_TARGET_HEIGHT
    cfg.rewards["foot_swing_height"].params["command_threshold"] = GAIT_ACTIVE_THRESHOLD
    cfg.rewards["foot_swing_height"].weight = -0.25
    cfg.rewards["foot_slip"].params["asset_cfg"].site_names = FOOT_SITES
    cfg.rewards["foot_slip"].weight = -1.0  # (m/s)^2 per stance foot
    # mjlab gates on command > threshold; -1 = always on (also while standing).
    cfg.rewards["foot_slip"].params["command_threshold"] = -1.0
    cfg.rewards["feet_flat"] = RewardTermCfg(
        func=microduck_mdp.feet_tilt_near_ground,
        weight=-2.0,  # 10 deg sole tilt -> 0.06/step
        params={"sensor_name": feet_ground_cfg.name, "height_threshold": 0.02, "asset_cfg": deepcopy(feet)},
    )
    cfg.rewards["touchdown_velocity"] = RewardTermCfg(
        func=microduck_mdp.feet_touchdown_velocity,
        weight=-2.0,  # 0.3 m/s downward at touchdown -> 0.18 per footfall
        params={"sensor_name": feet_ground_cfg.name, "asset_cfg": deepcopy(feet)},
    )
    cfg.rewards["soft_landing"].params["command_threshold"] = -1.0  # always on
    cfg.rewards["feet_spacing"] = RewardTermCfg(
        func=microduck_mdp.feet_lateral_spacing,
        weight=-10.0,  # 2 cm outside the band -> 0.2/step
        params={
            "min_spacing": FEET_LATERAL_SPACING[0],
            "max_spacing": FEET_LATERAL_SPACING[1],
            "asset_cfg": deepcopy(feet),
        },
    )
    cfg.rewards["hip_yaw_roll"] = RewardTermCfg(
        func=microduck_mdp.joint_deviation_l2,
        weight=-1.0,  # 0.15 rad on two joints -> 0.045/step
        params={"asset_cfg": SceneEntityCfg("robot", joint_names=(r".*_hip_yaw", r".*_hip_roll"))},
    )

    cfg.rewards["action_rate_l2"].weight = -0.05  # ramped by curriculum below

    # Torques: 10 joints at ~3 Nm rms -> ~90 Nm^2 -> -0.018/step.
    cfg.rewards["joint_torques"] = RewardTermCfg(func=mdp.joint_torques_l2, weight=-2.0e-4)

    cfg.rewards["self_collisions"] = RewardTermCfg(
        func=mdp.self_collision_cost,
        weight=-1.0,
        params={"sensor_name": self_collision_cfg.name, "force_threshold": 10.0},
    )

    # Pose-dependent knee limit (robot/model.py knee_max). COST (>= 0) -> negative
    # weight. 0.1 rad overshoot costs 1.0/step, comparable to a tracking term.
    cfg.rewards["knee_limit"] = RewardTermCfg(
        func=microduck_mdp.qdd_knee_limit_cost,
        weight=-10.0,
        params={"margin": KNEE_LIMIT_MARGIN},
    )

    # --- Terminations ------------------------------------------------------------
    cfg.terminations["fell_over"].params["limit_angle"] = math.radians(60.0)
    cfg.terminations["torso_low"] = TerminationTermCfg(
        func=mdp.root_height_below_minimum,
        params={"minimum_height": 0.20},  # standing 0.344, full 120 deg crouch ~0.23
    )
    cfg.terminations["body_ground_contact"] = TerminationTermCfg(
        func=mdp.illegal_contact,
        params={"sensor_name": body_ground_cfg.name},
    )
    cfg.terminations["knee_limit"] = TerminationTermCfg(
        func=microduck_mdp.qdd_knee_limit_exceeded,
        params={"tolerance": KNEE_LIMIT_TERMINATION_TOL},
    )
    cfg.terminations["nan_state"] = TerminationTermCfg(
        func=microduck_mdp.robot_state_is_nan,
        time_out=False,
        params={"sensor_names": (feet_ground_cfg.name,)},
    )
    cfg.terminations.pop("out_of_terrain_bounds", None)

    # --- Events / domain randomization -------------------------------------------
    # Spawn: the default root pos already has the soles on the floor (STAND_BASE_Z).
    cfg.events["reset_base"].params["pose_range"]["z"] = (0.0, 0.005)
    cfg.events["foot_friction"].params["asset_cfg"].geom_names = FOOT_GEOMS
    cfg.events["foot_friction"].params["ranges"] = FOOT_FRICTION_RANGE

    if ENABLE_COM_RANDOMIZATION:
        cfg.events["base_com"].params["asset_cfg"].body_names = (TORSO_BODY,)
        cfg.events["base_com"].params["ranges"] = COM_RANDOMIZATION_RANGE
    else:
        cfg.events.pop("base_com", None)

    if ENABLE_ENCODER_BIAS:
        cfg.events["encoder_bias"].params["bias_range"] = ENCODER_BIAS_RANGE
    else:
        cfg.events.pop("encoder_bias", None)

    if ENABLE_VELOCITY_PUSHES and not play:
        cfg.events["push_robot"] = EventTermCfg(
            func=mdp.push_by_setting_velocity,
            mode="interval",
            interval_range_s=VELOCITY_PUSH_INTERVAL_S,
            params={
                "velocity_range": {"x": VELOCITY_PUSH_RANGE, "y": VELOCITY_PUSH_RANGE},
                "asset_cfg": SceneEntityCfg("robot"),
            },
        )
    else:
        cfg.events.pop("push_robot", None)

    if ENABLE_MASS_INERTIA_RANDOMIZATION:
        lo, hi = MASS_INERTIA_RANDOMIZATION_RANGE
        cfg.events["randomize_mass_inertia"] = EventTermCfg(
            func=dr.pseudo_inertia,
            mode="startup",
            params={
                "asset_cfg": SceneEntityCfg("robot", body_names=(TORSO_BODY,)),
                "alpha_range": (math.log(lo) / 2.0, math.log(hi) / 2.0),
            },
        )

    if ENABLE_PD_GAIN_RANDOMIZATION:
        cfg.events["randomize_pd_gains"] = EventTermCfg(
            func=dr.pd_gains,
            mode="reset",
            params={
                "asset_cfg": SceneEntityCfg("robot"),
                "kp_range": KP_RANDOMIZATION_RANGE,
                "kd_range": KD_RANDOMIZATION_RANGE,
                "operation": "scale",
            },
        )

    if ENABLE_EFFORT_LIMIT_RANDOMIZATION:
        cfg.events["randomize_effort_limits"] = EventTermCfg(
            func=dr.effort_limits,
            mode="reset",
            params={
                "asset_cfg": SceneEntityCfg("robot"),
                "effort_limit_range": EFFORT_LIMIT_RANDOMIZATION_RANGE,
                "operation": "scale",
            },
        )

    if ENABLE_ARMATURE_RANDOMIZATION:
        cfg.events["randomize_armature"] = EventTermCfg(
            func=dr.joint_armature,
            mode="reset",
            params={
                "asset_cfg": SceneEntityCfg("robot", joint_names=(r".*",)),
                "operation": "scale",
                "ranges": ARMATURE_RANDOMIZATION_RANGE,
            },
        )

    if ENABLE_JOINT_FRICTION_RANDOMIZATION:
        cfg.events["randomize_joint_friction"] = EventTermCfg(
            func=dr.joint_friction,
            mode="reset",
            params={
                "asset_cfg": SceneEntityCfg("robot", joint_names=(r".*",)),
                "operation": "scale",
                "ranges": JOINT_FRICTION_RANDOMIZATION_RANGE,
            },
        )

    # --- Observations ------------------------------------------------------------
    actor = cfg.observations["actor"].terms
    critic = cfg.observations["critic"].terms
    del actor["base_lin_vel"]  # not measurable on the robot
    del actor["height_scan"]
    del critic["height_scan"]
    critic["base_lin_vel"] = ObservationTermCfg(func=mdp.base_lin_vel)  # privileged

    # Actor and critic share term objects from the template: copy before mutating.
    for name in ("base_ang_vel", "projected_gravity", "joint_pos", "joint_vel"):
        actor[name] = deepcopy(actor[name])
        critic[name] = deepcopy(critic[name])

    # IMU path (BNO085 / ICM-42688 on the Pi): 0-1 policy-step delay.
    for name in ("base_ang_vel", "projected_gravity"):
        actor[name].delay_min_lag = 0
        actor[name].delay_max_lag = 1
        actor[name].delay_update_period = 64
    actor["base_ang_vel"].noise = Unoise(n_min=-0.05, n_max=0.05)
    actor["projected_gravity"].noise = Unoise(n_min=-0.02, n_max=0.02)
    actor["joint_pos"].noise = Unoise(n_min=-0.005, n_max=0.005)
    actor["joint_vel"].noise = Unoise(n_min=-0.3, n_max=0.3)

    if ENABLE_IMU_ORIENTATION_RANDOMIZATION:
        actor["base_ang_vel"].func = microduck_mdp.base_ang_vel_imu_misaligned
        actor["base_ang_vel"].params = {"max_angle_deg": IMU_ORIENTATION_RANDOMIZATION_ANGLE}
        actor["projected_gravity"].func = microduck_mdp.projected_gravity_imu_misaligned
        actor["projected_gravity"].params = {"max_angle_deg": IMU_ORIENTATION_RANDOMIZATION_ANGLE}

    # Encoder bias is what the policy sees; the critic keeps the true joint pos.
    actor["joint_pos"].params["biased"] = ENABLE_ENCODER_BIAS
    critic["joint_pos"].params["biased"] = False

    # Gait clock, last actor term (policy_io.json "gait_phase"). Exact (no noise,
    # no delay): the robot computes it itself.
    actor["gait_phase"] = ObservationTermCfg(
        func=microduck_mdp.gait_phase_obs, params={"command_name": "gait"}
    )
    critic["gait_phase"] = ObservationTermCfg(
        func=microduck_mdp.gait_phase_obs, params={"command_name": "gait"}
    )

    for term, safe in (
        ("foot_contact_forces", microduck_mdp.foot_contact_forces_safe),
        ("foot_height", microduck_mdp.foot_height_safe),
        ("foot_air_time", microduck_mdp.foot_air_time_safe),
    ):
        if term in critic:
            critic[term] = deepcopy(critic[term])
            critic[term].func = safe

    # --- Curricula ---------------------------------------------------------------
    cfg.curriculum.pop("terrain_levels", None)
    cfg.curriculum.pop("command_vel", None)
    cfg.curriculum["action_rate_weight"] = CurriculumTermCfg(
        func=microduck_mdp.reward_weight,
        params={
            "reward_name": "action_rate_l2",
            "weight_stages": [
                {"step": 0, "weight": -0.05},
                {"step": 250 * NUM_STEPS_PER_ENV, "weight": -0.1},
                {"step": 500 * NUM_STEPS_PER_ENV, "weight": -0.2},
                {"step": 750 * NUM_STEPS_PER_ENV, "weight": -0.3},
            ],
        },
    )
    cfg.curriculum["standing_envs"] = CurriculumTermCfg(
        func=microduck_mdp.standing_envs_curriculum,
        params={
            "command_name": "twist",
            "standing_stages": [
                {"step": 0, "rel_standing_envs": 0.05},
                {"step": 250 * NUM_STEPS_PER_ENV, "rel_standing_envs": 0.1},
                {"step": 500 * NUM_STEPS_PER_ENV, "rel_standing_envs": 0.15},
                {"step": 750 * NUM_STEPS_PER_ENV, "rel_standing_envs": 0.2},
            ],
        },
    )

    # --- Play mode (export / video) ------------------------------------------------
    if play:
        _make_play_nominal(cfg)

    return cfg


def _make_play_nominal(cfg: ManagerBasedRlEnvCfg) -> None:
    """Play mode (scripts/export.py, yatai snapshots / video): the nominal robot
    (no DR, pushes, obs noise / delay / IMU misalignment / encoder bias, fixed
    mid-range command latency) following PLAY_COMMAND_SCHEDULE, so the video
    shows the policy itself. Obs layout is unchanged (policy_io.json)."""
    from dataclasses import replace

    cfg.episode_length_s = int(1e9)
    cfg.curriculum = {}
    for name in (
        "push_robot",
        "base_com",
        "encoder_bias",
        "foot_friction",  # -> nominal 0.8 from the collision cfg
        "randomize_mass_inertia",
        "randomize_pd_gains",
        "randomize_effort_limits",
        "randomize_armature",
        "randomize_joint_friction",
    ):
        cfg.events.pop(name, None)
    actor = cfg.observations["actor"]
    actor.enable_corruption = False
    for term in actor.terms.values():
        term.delay_min_lag = term.delay_max_lag = 0
    for name in ("base_ang_vel", "projected_gravity"):
        if "max_angle_deg" in actor.terms[name].params:
            actor.terms[name].params["max_angle_deg"] = 0.0
    actor.terms["joint_pos"].params["biased"] = False
    robot = cfg.scene.entities["robot"]
    art = robot.articulation  # module-level QDD_ARTICULATION: replace, never mutate
    robot.articulation = replace(
        art, actuators=tuple(replace(a, delay_min_lag=1, delay_max_lag=1) for a in art.actuators)
    )

    twist = cfg.commands["twist"]
    cfg.commands["twist"] = microduck_mdp.ScheduledVelocityCommandCfg(
        **vars(twist), schedule=PLAY_COMMAND_SCHEDULE, schedule_period_s=PLAY_SCHEDULE_PERIOD_S
    )
    cfg.commands["twist"].resampling_time_range = (1.0e9, 1.0e9)
    cfg.commands["twist"].rel_standing_envs = 0.0


