def build_policy_io() -> dict:
    """The policy I/O contract as a JSON-serialisable dict (single source of truth)."""
    from mjlab_microduck.robot import qdd_biped_constants as rc

    cfg = make_qdd_biped_velocity_env_cfg(play=True)
    step_dt = cfg.sim.mujoco.timestep * cfg.decimation

    def per_joint(table: dict) -> list[float]:
        import re

        out = []
        for name in QDD_JOINT_NAMES:
            vals = [v for pat, v in table.items() if re.fullmatch(pat, name)]
            assert len(vals) == 1, (name, vals)
            out.append(float(vals[0]))
        return out

    default_q = per_joint(rc.DEFAULT_JOINT_POS)
    kp, kd, effort = [], [], []
    for name in QDD_JOINT_NAMES:
        if name.endswith(("hip_yaw", "hip_roll")):
            a = rc.QDD_ACTUATOR_HIP_YAW_ROLL
        elif name.endswith(("hip_pitch", "knee")):
            a = rc.QDD_ACTUATOR_HIP_PITCH_KNEE
        else:
            a = rc.QDD_ACTUATOR_ANKLE
        kp.append(float(a.stiffness))
        kd.append(float(a.damping))
        effort.append(float(a.effort_limit))

    m = rc.get_qdd_biped_spec().compile()
    joint_limits = [[round(float(x), 6) for x in m.joint(n).range] for n in QDD_JOINT_NAMES]

    terms = []
    start = 0
    for name in cfg.observations["actor"].terms:
        spec = _ACTOR_OBS_SPEC[name]  # KeyError = new actor term: describe it here
        terms.append({"name": name, "start": start, **spec})
        start += spec["size"]

    twist = cfg.commands["twist"]
    gait = cfg.commands["gait"]
    return {
        "schema_version": POLICY_IO_SCHEMA_VERSION,
        "task": TASK_ID,
        "control_rate_hz": round(1.0 / step_dt, 6),
        "policy_dt_s": step_dt,
        "onnx": {
            "input": {"name": "obs", "shape": [1, start], "dtype": "float32"},
            "output": {"name": "actions", "shape": [1, _N], "dtype": "float32"},
            "obs_normalization": "baked into the ONNX graph: feed RAW observations",
            "output_is": "deterministic action mean",
        },
        "action": {
            "dim": _N,
            "joint_order": list(QDD_JOINT_NAMES),
            "scale": float(QDD_ACTION_SCALE),
            "default_joint_pos": default_q,
            "target": "q_target = default_joint_pos + scale * action",
            "clip": None,
            "filter": None,
        },
        "actuators": {
            "mode": "driver-side PD (MIT mode, >= 1 kHz): tau = kp * (q_target - q) - kd * qd, "
            "clamped to +/- effort_limit",
            "joint_order": list(QDD_JOINT_NAMES),
            "kp_nm_per_rad": kp,
            "kd_nm_s_per_rad": kd,
            "effort_limit_nm": effort,
            "joint_pos_limits_rad": joint_limits,
            "knee_max_note": "pose-dependent knee limit knee_max(hip_pitch) from robot/model.py "
            "(80/90/100/110/120 deg for hip_pitch > 0/-15/-30/-45/else deg) must be enforced "
            "by the safety layer",
        },
        "observation": {
            "dim": start,
            "history_length": 1,
            "scaling": "none (all terms in the units listed)",
            "clip": None,
            "terms": terms,
        },
        "gait_clock": {
            "period_s": float(gait.period_s),
            "swing_fraction": float(gait.swing_fraction),
            "active_threshold": float(gait.active_threshold),
            "active_rule": "active = (hypot(vx, vy) + abs(wz)) > active_threshold, "
            "evaluated on the command fed to the policy at this step",
            "update_rule": "every policy step, BEFORE building the observation: "
            "if active: phi = (phi + policy_dt_s / period_s) mod 1; else phi unchanged (paused)",
            "initial_phase": 0.0,
            "observation": "gait_phase = [sin(2 pi phi), cos(2 pi phi)]",
            "schedule": "left leg swings for phi in [0, swing_fraction), right leg for "
            "(phi + 0.5) mod 1 in [0, swing_fraction); otherwise stance; paused -> both stance",
        },
        "commands": {
            "lin_vel_x_range": list(twist.ranges.lin_vel_x),
            "lin_vel_y_range": list(twist.ranges.lin_vel_y),
            "ang_vel_z_range": list(twist.ranges.ang_vel_z),
            "standing": "command [0, 0, 0] (gait clock pauses, both feet down)",
        },
    }


def policy_io_json() -> str:
    import json

    return json.dumps(build_policy_io(), indent=2) + "\n"


def write_policy_io(path=None) -> str:
    from pathlib import Path

    from mjlab_microduck.robot.qdd_biped_constants import QDD_POLICY_IO_JSON

    path = Path(path) if path is not None else QDD_POLICY_IO_JSON
    path.write_text(policy_io_json(), encoding="utf-8", newline="\n")
    return str(path)


def policy_io_onnx_metadata() -> dict[str, str]:
    """ONNX metadata_props carrying the committed policy_io.json verbatim + its
    sha256 (the controller can check the hash against its own copy)."""
    import hashlib

    from mjlab_microduck.robot.qdd_biped_constants import QDD_POLICY_IO_JSON

    text = QDD_POLICY_IO_JSON.read_text(encoding="utf-8")
    return {
        "policy_io": text,
        "policy_io_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
    }


