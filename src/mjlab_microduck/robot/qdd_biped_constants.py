"""QDD biped (6.61 kg,
 ~0.52 m, 10 quasi-direct-drive joints) robot cfg for mjlab.

Source of truth is the robot repo (robot/model.py); qdd_biped/qdd_biped.xml is
generated from it by qdd_biped/generate_mjcf.py. Values copied here by hand:

  MOTORS (robot/model.py)
    GIM6010-8   hip_yaw / hip_roll / hip_pitch / knee : peak 11 Nm, 44 rad/s,
                armature 6e-5 * 8^2 = 3.84e-3 kg m^2
    GIM3510-8   ankle_pitch                           : peak 6.28 Nm, 42.4 rad/s,
                armature 1.5e-5 * 10^2 = 1.5e-3 kg m^2
  (armature is already in the XML joints; not overridden here.)

Unlike the microduck (Dynamixel XL330, BAM voltage model), these drivers run the
PD loop themselves in MIT mode at >= 1 kHz from position targets sent at 50 Hz,
so the sim actuator is MuJoCo's built-in position PD (implicit, physics rate)
with an effort clamp at peak torque. The SAME Kp/Kd must be programmed into the
drivers on the real robot (they are exported in the ONNX metadata).

Gain choice (checked in plain MuJoCo, 5 s stand at the default pose: settles,
feet flat, ~4.5 deg backward torso lean from PD sag that the policy corrects):
  hip_pitch / knee : Kp 40 Nm/rad, Kd 1.2  (knee ~critically damped for the
                     shank+foot+armature ~0.008 kg m^2; 1.6 Nm gravity load in
                     double support -> 0.04 rad sag)
  hip_yaw / roll   : Kp 30, Kd 1.0
  ankle_pitch      : Kp 20, Kd 0.6         (smaller motor, light foot)
"""

import math
import os
from pathlib import Path

import mujoco
from mjlab.actuator import BuiltinPositionActuatorCfg
from mjlab.entity import EntityArticulationInfoCfg, EntityCfg
from mjlab.utils.spec_config import CollisionCfg

QDD_BIPED_XML: Path = Path(os.path.dirname(__file__)) / "qdd_biped" / "qdd_biped.xml"
assert QDD_BIPED_XML.exists(), f"XML not found: {QDD_BIPED_XML}"
# Policy I/O contract for the real-robot controller (generated by
# tasks/qdd_biped_velocity_env_cfg.py build_policy_io / write_policy_io).
QDD_POLICY_IO_JSON: Path = Path(os.path.dirname(__file__)) / "qdd_biped" / "policy_io.json"

# Names (as in robot/model.py JOINT_NAMES): {l,r}_{hip_yaw,hip_roll,hip_pitch,knee,ankle_pitch}
# Action / obs order = XML joint order: l_hip_yaw .. l_ankle_pitch, r_hip_yaw .. r_ankle_pitch.
QDD_JOINT_NAMES = tuple(
    f"{s}_{j}" for s in ("l", "r") for j in ("hip_yaw", "hip_roll", "hip_pitch", "knee", "ankle_pitch")
)
TORSO_BODY = "torso"
FOOT_SITES = ("l_foot_site", "r_foot_site")
FOOT_GEOMS = ("l_foot_collision", "r_foot_collision")

# --- Default pose: robot/model.py crouch_pose(45 deg) --------------------------
CROUCH_KNEE_DEG = 45.0
_k = math.radians(CROUCH_KNEE_DEG)
DEFAULT_JOINT_POS = {
    r".*_hip_yaw": 0.0,
    r".*_hip_roll": 0.0,
    r".*_hip_pitch": -_k / 2,
    r".*_knee": _k,
    r".*_ankle_pitch": -_k / 2,
}
# Torso-origin height with the soles on the floor in that pose: yaw->roll 0.064 +
# 2 * 0.13 * cos(22.5 deg) + ankle->sole 0.050 = 0.3542 m (checked with MuJoCo).
# ankle->sole = PA12 sole 40 mm + 10 mm TPU landing pad (robot repo 31cceba).
STAND_BASE_Z = 0.3542

HOME_FRAME = EntityCfg.InitialStateCfg(
    pos=(0.0, 0.0, STAND_BASE_Z + 0.005),
    joint_pos=DEFAULT_JOINT_POS,
    joint_vel={".*": 0.0},
)

# --- Actuators -----------------------------------------------------------------
GIM6010_PEAK = 11.0
ANKLE_PEAK = 6.28   # GIM3510-8 (GDZ34 + output-side encoder)

HIP_YAW_ROLL_KP, HIP_YAW_ROLL_KD = 30.0, 1.0
HIP_PITCH_KNEE_KP, HIP_PITCH_KNEE_KD = 40.0, 1.2
ANKLE_KP, ANKLE_KD = 20.0, 0.6

# Command latency: policy (Pi 5) -> CAN -> driver. 0-2 physics steps of 5 ms
# (0-10 ms), resampled per env.
_DELAY = dict(delay_min_lag=0, delay_max_lag=2)

QDD_ACTUATOR_HIP_YAW_ROLL = BuiltinPositionActuatorCfg(
    target_names_expr=(r".*_hip_yaw", r".*_hip_roll"),
    stiffness=HIP_YAW_ROLL_KP,
    damping=HIP_YAW_ROLL_KD,
    effort_limit=GIM6010_PEAK,
    **_DELAY,
)
QDD_ACTUATOR_HIP_PITCH_KNEE = BuiltinPositionActuatorCfg(
    target_names_expr=(r".*_hip_pitch", r".*_knee"),
    stiffness=HIP_PITCH_KNEE_KP,
    damping=HIP_PITCH_KNEE_KD,
    effort_limit=GIM6010_PEAK,
    **_DELAY,
)
QDD_ACTUATOR_ANKLE = BuiltinPositionActuatorCfg(
    target_names_expr=(r".*_ankle_pitch",),
    stiffness=ANKLE_KP,
    damping=ANKLE_KD,
    effort_limit=ANKLE_PEAK,
    **_DELAY,
)

QDD_ARTICULATION = EntityArticulationInfoCfg(
    actuators=(QDD_ACTUATOR_HIP_YAW_ROLL, QDD_ACTUATOR_HIP_PITCH_KNEE, QDD_ACTUATOR_ANKLE),
    soft_joint_pos_limit_factor=0.9,
)

# Action scale (rad per unit action). The mjlab G1 rule 0.25 * effort / Kp gives
# 0.069-0.092 rad here, too small for a 0.13 m-link leg to step with unit-std
# exploration; 0.25 rad keeps initial exploration at about +/-15 deg per joint.
QDD_ACTION_SCALE = 0.25

# --- Collisions ------------------------------------------------------------------
# Feet: condim 3 (friction) + priority so their friction wins vs the floor.
# Everything else (torso boxes, thigh/shank capsules, knee-motor spheres):
# condim 1, used to detect falls (torso) and leg-leg self-collision.
FULL_COLLISION = CollisionCfg(
    geom_names_expr=(r".*_collision",),
    condim={r"^(l|r)_foot_collision$": 3, r".*_collision": 1},
    priority={r"^(l|r)_foot_collision$": 1},
    friction={r"^(l|r)_foot_collision$": (0.8,)},
)


def get_qdd_biped_spec() -> mujoco.MjSpec:
    return mujoco.MjSpec.from_file(str(QDD_BIPED_XML))


def get_qdd_biped_robot_cfg() -> EntityCfg:
    """Fresh cfg each call (cfgs are mutated by env factories)."""
    return EntityCfg(
        spec_fn=get_qdd_biped_spec,
        init_state=HOME_FRAME,
        collisions=(FULL_COLLISION,),
        articulation=QDD_ARTICULATION,
    )


def knee_max(hip_pitch_rad: float) -> float:
    """Pose-dependent knee limit [rad] — verbatim port of robot/model.py knee_max."""
    hp = math.degrees(hip_pitch_rad)
    k = 80 if hp > 0 else 90 if hp > -15 else 100 if hp > -30 else 110 if hp > -45 else 120
    return math.radians(k)


# =============================================================================
# Get-up (Mjlab-Getup-QddBiped): the robot lies on the floor, so every part that
# can touch it needs a collision shape WITH friction (the walking model uses
# frictionless condim-1 shapes only to detect a fall).
#   - the walking collision shapes (torso boxes, thigh / shank capsules, knee
#     spheres, soles) get condim 3 and friction,
#   - the motor housings (blue visual cylinders: hip yaw / roll / pitch, knee,
#     ankle) and the rabbit top of the torso get extra collision shapes. These
#     touch the FLOOR only (contype 2 / conaffinity 0; the floor's conaffinity
#     gets bit 2 in getup_scene_spec_fn), so the leg-leg self-collision check
#     of the walking model is unchanged.
# Not modelled: the rabbit ears (TPU, they bend) and the exact cover shapes
# (roll_cap, shell_bumper_rear, knee_pad, shank_cover): the robot repo's
# analysis/fall_sim.py uses the CAD meshes; check a trained get-up there.
# =============================================================================
GETUP_FLOOR_BIT = 2
# Fallen-state library (scripts/qdd_getup_states.py): resting poses after falls.
QDD_GETUP_POLICY_IO_JSON: Path = Path(os.path.dirname(__file__)) / "qdd_biped" / "policy_io_getup.json"
QDD_GETUP_STATES_NPZ: Path = Path(os.path.dirname(__file__)) / "qdd_biped" / "getup_states.npz"
MOTOR_VISUAL_RGBA = (0.15, 0.35, 0.75, 1.0)
# Rabbit face + hatch on top of the torso (robot/model.py TORSO_ITEMS "rabbit"):
# visual box centre / half sizes in the torso frame.
TORSO_TOP_BOX = ((0.0157, 0.0, 0.15), (0.05, 0.08, 0.03))
BODY_FRICTION = 0.6  # PA12 / TPU covers on a floor (randomised in the get-up env)


def add_getup_collision_geoms(spec: mujoco.MjSpec) -> list[str]:
    """Add floor-only collision shapes for the motor housings and the rabbit top
    (see above). Returns the names of the added geoms."""
    added: list[str] = []
    for body in spec.bodies:
        if body.name == "world":
            continue
        motors = [
            g
            for g in body.geoms
            if g.type == mujoco.mjtGeom.mjGEOM_CYLINDER
            and g.contype == 0
            and all(abs(a - b) < 1e-3 for a, b in zip(g.rgba, MOTOR_VISUAL_RGBA))
        ]
        for i, g in enumerate(motors):
            name = f"{body.name}_motor{i}_collision"
            body.add_geom(
                name=name,
                type=mujoco.mjtGeom.mjGEOM_CYLINDER,
                fromto=list(g.fromto),
                size=list(g.size),
                contype=GETUP_FLOOR_BIT,
                conaffinity=0,
                condim=3,
                priority=1,
                friction=(BODY_FRICTION, 0.02, 0.01),
                group=3,
                mass=0.0,
                density=0.0,
            )
            added.append(name)
        if body.name == TORSO_BODY:
            pos, half = TORSO_TOP_BOX
            body.add_geom(
                name="torso_top_collision",
                type=mujoco.mjtGeom.mjGEOM_BOX,
                pos=list(pos),
                size=list(half),
                contype=GETUP_FLOOR_BIT,
                conaffinity=0,
                condim=3,
                priority=1,
                friction=(BODY_FRICTION, 0.02, 0.01),
                group=3,
                mass=0.0,
                density=0.0,
            )
            added.append("torso_top_collision")
    return added


def get_qdd_biped_getup_spec() -> mujoco.MjSpec:
    spec = get_qdd_biped_spec()
    add_getup_collision_geoms(spec)
    return spec


# Every collision shape with friction; soles keep their own friction (priority).
_FLOOR_ONLY = r"^(.*_motor\d+_collision|torso_top_collision)$"
GETUP_COLLISION = CollisionCfg(
    geom_names_expr=(r".*_collision",),
    contype={_FLOOR_ONLY: GETUP_FLOOR_BIT, r".*_collision": 1},
    conaffinity={_FLOOR_ONLY: 0, r".*_collision": 1},
    condim={r".*_collision": 3},
    priority={r".*_collision": 1},
    friction={r"^(l|r)_foot_collision$": (0.8,), r".*_collision": (BODY_FRICTION,)},
)


def get_qdd_biped_getup_robot_cfg() -> EntityCfg:
    return EntityCfg(
        spec_fn=get_qdd_biped_getup_spec,
        init_state=HOME_FRAME,
        collisions=(GETUP_COLLISION,),
        articulation=QDD_ARTICULATION,
    )


def getup_scene_spec_fn(spec: mujoco.MjSpec) -> None:
    """Scene spec_fn: let the floor collide with the floor-only shapes."""
    terrain = spec.body("terrain")
    for g in terrain.geoms:
        g.conaffinity = g.conaffinity | GETUP_FLOOR_BIT
